-- =====================================================================
-- SQL 50 — Banners pagos de empresas no carrossel do Início
-- Idempotente (pode rodar mais de uma vez). Sem barras invertidas.
--
--  * banners_pagos      : banner do usuário (imagem no bucket 'banners/<auth_id>/...')
--      status: aguardando_pagamento | comprovante_enviado | ativo | bloqueado | recusado
--      "vencido" = status 'ativo' com ativo_ate <= now() (some do carrossel pela consulta)
--      Renovação de banner ativo: renovacao_pedida_em (status continua 'ativo' até vencer)
--  * banner_pagamentos  : log de pagamentos confirmados pelo admin (valor, quem, quando)
--  * app_flags 'banner_preco_mensal' (value_text '99.90') — editável pelo admin
--
--  Usuário: cria/vê/apaga só os SEUS; não mexe em status/ativo_ate (gatilho + sem UPDATE).
--  Admin: tudo, via RPCs SECURITY DEFINER com checagem is_admin().
--  Público (anon/authenticated): lê só ativos e não vencidos.
-- =====================================================================

-- 1) Tabelas ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.banners_pagos (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id             uuid NOT NULL DEFAULT auth.uid(),
  imagem_url          text NOT NULL,
  titulo              text,
  link                text,
  whatsapp            text,
  status              text NOT NULL DEFAULT 'aguardando_pagamento',
  ativo_ate           timestamptz,
  liberado_em         timestamptz,
  comprovante_em      timestamptz,
  renovacao_pedida_em timestamptz,
  motivo              text,
  criado_em           timestamptz NOT NULL DEFAULT now(),
  atualizado_em       timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.banners_pagos ADD COLUMN IF NOT EXISTS comprovante_em timestamptz;
ALTER TABLE public.banners_pagos ADD COLUMN IF NOT EXISTS renovacao_pedida_em timestamptz;
ALTER TABLE public.banners_pagos ADD COLUMN IF NOT EXISTS motivo text;

ALTER TABLE public.banners_pagos DROP CONSTRAINT IF EXISTS banners_pagos_status_chk;
ALTER TABLE public.banners_pagos ADD CONSTRAINT banners_pagos_status_chk
  CHECK (status IN ('aguardando_pagamento', 'comprovante_enviado', 'ativo', 'bloqueado', 'recusado'));
ALTER TABLE public.banners_pagos DROP CONSTRAINT IF EXISTS banners_pagos_titulo_len;
ALTER TABLE public.banners_pagos ADD CONSTRAINT banners_pagos_titulo_len
  CHECK (titulo IS NULL OR char_length(titulo) <= 60);
ALTER TABLE public.banners_pagos DROP CONSTRAINT IF EXISTS banners_pagos_link_len;
ALTER TABLE public.banners_pagos ADD CONSTRAINT banners_pagos_link_len
  CHECK (link IS NULL OR char_length(link) <= 300);

CREATE INDEX IF NOT EXISTS banners_pagos_auth_idx ON public.banners_pagos (auth_id);
CREATE INDEX IF NOT EXISTS banners_pagos_ativos_idx ON public.banners_pagos (status, ativo_ate);

CREATE TABLE IF NOT EXISTS public.banner_pagamentos (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  banner_id      bigint REFERENCES public.banners_pagos(id) ON DELETE SET NULL,
  auth_id        uuid,                 -- dono do banner (fica mesmo se o banner for apagado)
  valor          numeric(10,2) NOT NULL,
  dias           int NOT NULL DEFAULT 30,
  ativo_ate_novo timestamptz,
  confirmado_por uuid,
  confirmado_em  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS banner_pagamentos_banner_idx ON public.banner_pagamentos (banner_id);
CREATE INDEX IF NOT EXISTS banner_pagamentos_mes_idx ON public.banner_pagamentos (confirmado_em);

-- 2) Preço editável (app_flags do SQL 35) ------------------------------
INSERT INTO public.app_flags (key, value_text)
VALUES ('banner_preco_mensal', '99.90')
ON CONFLICT (key) DO NOTHING;

CREATE OR REPLACE FUNCTION public.banner_preco()
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    (SELECT CASE WHEN replace(value_text, ',', '.') ~ '^[0-9]+([.][0-9]{1,2})?$'
                 THEN replace(value_text, ',', '.')::numeric END
       FROM public.app_flags WHERE key = 'banner_preco_mensal'),
    99.90);
$$;

-- 3) Gatilho: usuário não escolhe status/datas; valida imagem/link/whatsapp
CREATE OR REPLACE FUNCTION public.banners_pagos_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_admin boolean := COALESCE(public.is_admin(), false);
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NOT v_admin THEN
      IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'banner: login necessário' USING ERRCODE = '42501';
      END IF;
      NEW.auth_id := auth.uid();
      NEW.status := 'aguardando_pagamento';
      NEW.ativo_ate := NULL;
      NEW.liberado_em := NULL;
      NEW.comprovante_em := NULL;
      NEW.renovacao_pedida_em := NULL;
      NEW.motivo := NULL;
      -- só imagem do próprio usuário no bucket 'banners'
      IF position('/storage/v1/object/public/banners/' || auth.uid()::text || '/' IN COALESCE(NEW.imagem_url, '')) = 0 THEN
        RAISE EXCEPTION 'banner: imagem inválida' USING ERRCODE = '22023';
      END IF;
    END IF;
    NEW.criado_em := now();
  END IF;
  NEW.titulo := NULLIF(btrim(COALESCE(NEW.titulo, '')), '');
  NEW.link := NULLIF(btrim(COALESCE(NEW.link, '')), '');
  IF NEW.link IS NOT NULL AND NEW.link !~* '^https?://[^ ]+$' THEN
    NEW.link := NULL;
  END IF;
  NEW.whatsapp := NULLIF(regexp_replace(COALESCE(NEW.whatsapp, ''), '[^0-9]', '', 'g'), '');
  IF NEW.whatsapp IS NOT NULL AND char_length(NEW.whatsapp) NOT BETWEEN 10 AND 13 THEN
    NEW.whatsapp := NULL;
  END IF;
  NEW.atualizado_em := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_banners_pagos_guard ON public.banners_pagos;
CREATE TRIGGER trg_banners_pagos_guard
  BEFORE INSERT OR UPDATE ON public.banners_pagos
  FOR EACH ROW EXECUTE FUNCTION public.banners_pagos_guard();

