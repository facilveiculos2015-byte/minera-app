-- 7) Conferência: esperado tabelas=2 | rpcs=8 | gatilho=1 | bucket=1 | policies_storage=4 | policies_tabelas=7 | preco=99.90 (ou o valor salvo)
SELECT
  (SELECT count(*) FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name IN ('banners_pagos', 'banner_pagamentos')) AS tabelas,
  (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.proname IN ('banner_preco', 'banners_pagos_ativos', 'banner_marcar_comprovante',
      'banner_pedir_renovacao', 'banner_admin_liberar', 'banner_admin_status', 'banner_admin_lista', 'banner_admin_totais_mes')) AS rpcs,
  (SELECT count(*) FROM pg_trigger WHERE tgname = 'trg_banners_pagos_guard') AS gatilho,
  (SELECT count(*) FROM storage.buckets WHERE id = 'banners') AS bucket,
  (SELECT count(*) FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname IN ('banners_select_public', 'banners_insert_own', 'banners_update_own', 'banners_delete_own')) AS policies_storage,
  (SELECT count(*) FROM pg_policies WHERE schemaname = 'public' AND tablename IN ('banners_pagos', 'banner_pagamentos')) AS policies_tabelas,
  public.banner_preco() AS preco;
