-- 5) RPCs ----------------------------------------------------------------
-- Carrossel: ativos e não vencidos (sem expor dono)
DROP FUNCTION IF EXISTS public.banners_pagos_ativos();
CREATE FUNCTION public.banners_pagos_ativos()
RETURNS TABLE (id bigint, imagem_url text, titulo text, link text, whatsapp text, ativo_ate timestamptz)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT b.id, b.imagem_url, b.titulo, b.link, b.whatsapp, b.ativo_ate
    FROM public.banners_pagos b
   WHERE b.status = 'ativo' AND b.ativo_ate > now()
   ORDER BY b.liberado_em DESC NULLS LAST, b.id DESC
   LIMIT 30;
$$;

-- Dono: "Já enviei o comprovante"
CREATE OR REPLACE FUNCTION public.banner_marcar_comprovante(p_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  b public.banners_pagos;
BEGIN
  SELECT * INTO b FROM public.banners_pagos WHERE id = p_id AND auth_id = auth.uid();
  IF NOT FOUND THEN
    RAISE EXCEPTION 'banner: não encontrado' USING ERRCODE = 'P0002';
  END IF;
  IF b.status IN ('bloqueado', 'recusado') THEN
    RAISE EXCEPTION 'banner: %', b.status USING ERRCODE = '42501';
  END IF;
  UPDATE public.banners_pagos
     SET comprovante_em = now(),
         status = CASE WHEN status = 'aguardando_pagamento' THEN 'comprovante_enviado' ELSE status END
   WHERE id = p_id
   RETURNING status INTO b.status;
  RETURN b.status;
END;
$$;

-- Dono: "Renovar" (paga de novo; admin libera +30 dias a partir de max(now, ativo_ate))
CREATE OR REPLACE FUNCTION public.banner_pedir_renovacao(p_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  b public.banners_pagos;
BEGIN
  SELECT * INTO b FROM public.banners_pagos WHERE id = p_id AND auth_id = auth.uid();
  IF NOT FOUND THEN
    RAISE EXCEPTION 'banner: não encontrado' USING ERRCODE = 'P0002';
  END IF;
  IF b.status IN ('bloqueado', 'recusado') THEN
    RAISE EXCEPTION 'banner: %', b.status USING ERRCODE = '42501';
  END IF;
  UPDATE public.banners_pagos
     SET renovacao_pedida_em = CASE WHEN status = 'ativo' AND ativo_ate > now() THEN now() ELSE NULL END,
         comprovante_em = NULL,
         status = CASE WHEN status = 'ativo' AND ativo_ate > now() THEN 'ativo' ELSE 'aguardando_pagamento' END
   WHERE id = p_id
   RETURNING status INTO b.status;
  RETURN b.status;
END;
$$;

-- Admin: Liberar (registra pagamento do preço atual, +dias a partir de max(now, ativo_ate))
CREATE OR REPLACE FUNCTION public.banner_admin_liberar(p_id bigint, p_valor numeric DEFAULT NULL, p_dias int DEFAULT 30)
RETURNS timestamptz
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  b public.banners_pagos;
  v_ate timestamptz;
  v_valor numeric := COALESCE(p_valor, public.banner_preco());
  v_dias int := GREATEST(1, LEAST(COALESCE(p_dias, 30), 366));
BEGIN
  IF NOT COALESCE(public.is_admin(), false) THEN
    RAISE EXCEPTION 'banner: só admin' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO b FROM public.banners_pagos WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'banner: não encontrado' USING ERRCODE = 'P0002';
  END IF;
  v_ate := GREATEST(now(), COALESCE(b.ativo_ate, now())) + make_interval(days => v_dias);
  UPDATE public.banners_pagos
     SET status = 'ativo', ativo_ate = v_ate, liberado_em = now(),
         renovacao_pedida_em = NULL, comprovante_em = NULL, motivo = NULL
   WHERE id = p_id;
  INSERT INTO public.banner_pagamentos (banner_id, auth_id, valor, dias, ativo_ate_novo, confirmado_por)
  VALUES (p_id, b.auth_id, v_valor, v_dias, v_ate, auth.uid());
  RETURN v_ate;
END;
$$;

-- Admin: Bloquear / Recusar (ou voltar para aguardando)
CREATE OR REPLACE FUNCTION public.banner_admin_status(p_id bigint, p_status text, p_motivo text DEFAULT NULL)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT COALESCE(public.is_admin(), false) THEN
    RAISE EXCEPTION 'banner: só admin' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('bloqueado', 'recusado', 'aguardando_pagamento') THEN
    RAISE EXCEPTION 'banner: status inválido' USING ERRCODE = '22023';
  END IF;
  UPDATE public.banners_pagos
     SET status = p_status, motivo = NULLIF(btrim(COALESCE(p_motivo, '')), ''), renovacao_pedida_em = NULL
   WHERE id = p_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'banner: não encontrado' USING ERRCODE = 'P0002';
  END IF;
  RETURN p_status;
END;
$$;

-- Admin: lista com dono, contato e pagamentos
DROP FUNCTION IF EXISTS public.banner_admin_lista();
CREATE FUNCTION public.banner_admin_lista()
RETURNS TABLE (
  id bigint, auth_id uuid, imagem_url text, titulo text, link text, whatsapp text,
  status text, ativo_ate timestamptz, liberado_em timestamptz, comprovante_em timestamptz,
  renovacao_pedida_em timestamptz, motivo text, criado_em timestamptz,
  dono_nome text, dono_apelido text, dono_email text, dono_telefone text,
  n_pagamentos bigint, total_pago numeric, ultimo_valor numeric, ultimo_pagamento_em timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT COALESCE(public.is_admin(), false) THEN
    RAISE EXCEPTION 'banner: só admin' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT b.id, b.auth_id, b.imagem_url, b.titulo, b.link, b.whatsapp,
         b.status, b.ativo_ate, b.liberado_em, b.comprovante_em,
         b.renovacao_pedida_em, b.motivo, b.criado_em,
         u.nome::text, (to_jsonb(u) ->> 'apelido'), (to_jsonb(u) ->> 'email'),
         COALESCE(to_jsonb(u) ->> 'telefone', to_jsonb(u) ->> 'whatsapp'),
         COALESCE(p.n, 0), COALESCE(p.total, 0), p.ult_valor, p.ult_em
    FROM public.banners_pagos b
    LEFT JOIN LATERAL (SELECT * FROM public.usuarios x WHERE x.auth_id = b.auth_id LIMIT 1) u ON true
    LEFT JOIN LATERAL (
      SELECT count(*) AS n, sum(g.valor) AS total,
             (array_agg(g.valor ORDER BY g.confirmado_em DESC))[1] AS ult_valor,
             max(g.confirmado_em) AS ult_em
        FROM public.banner_pagamentos g WHERE g.banner_id = b.id
    ) p ON true
   ORDER BY b.criado_em DESC
   LIMIT 500;
END;
$$;

-- Admin: total recebido por mês (fuso de Belém)
DROP FUNCTION IF EXISTS public.banner_admin_totais_mes();
CREATE FUNCTION public.banner_admin_totais_mes()
RETURNS TABLE (mes text, n bigint, total numeric)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT COALESCE(public.is_admin(), false) THEN
    RAISE EXCEPTION 'banner: só admin' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT to_char(g.confirmado_em AT TIME ZONE 'America/Belem', 'YYYY-MM') AS mes, count(*), sum(g.valor)
    FROM public.banner_pagamentos g
   GROUP BY 1 ORDER BY 1 DESC LIMIT 24;
END;
$$;

